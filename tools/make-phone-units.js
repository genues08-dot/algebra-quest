// Writes js/phone-units.js, the units built into the online app (index.html) and the phone page
// (phone.html).
// Usage: node tools/make-phone-units.js units/<unit>.json [more unit files...]
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const units = require(path.join(__dirname, '../js/units.js'));

const files = process.argv.slice(2);
if (files.length === 0) {
  console.error('Usage: node tools/make-phone-units.js units/<unit>.json [more...]');
  process.exit(2);
}

const list = files.map(file => {
  const unit = JSON.parse(fs.readFileSync(file, 'utf8'));
  const result = units.validate(unit);
  if (!result.ok) {
    console.error(file + ' is not a valid unit:\n' + result.errors.join('\n'));
    process.exit(1);
  }
  return unit;
});

const out = path.join(__dirname, '../js/phone-units.js');
fs.writeFileSync(out,
  '// Generated by tools/make-phone-units.js. Do not edit by hand.\n' +
  'window.AQ_PHONE_UNITS = ' + JSON.stringify(list) + ';\n', 'utf8');
console.log('Wrote ' + out + ' with ' + list.map(u => u.title).join(', '));
